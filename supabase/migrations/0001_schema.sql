-- HydroSense: schema Hydrosense + tambahan LoRa (20 tabel).
-- Jalankan di SQL Editor (atau: supabase db push). Aman dijalankan ulang.
-- BERSIFAT MENAMBAH: di database groundtank yang sudah berisi data, tabel yang sudah
-- ada tidak dihapus atau dikosongkan. Yang berubah pada tabel groundtank hanya:
-- kolom LoRa ditambahkan ke `devices`, `sensor_readings.value` text -> numeric (jika
-- masih text), dan baris contoh di `sensors` / `devices` (on conflict do nothing).
--
-- Dua kelompok tabel:
--  1. KOMPATIBEL (12 tabel): nama tabel, kolom, dan tipe DISAMAKAN dengan yang dipakai
--     firmware (src/Network.cpp) dan dashboard (index.html) sekarang. Cukup ganti URL
--     dan key, tanpa ubah kode query. device_id di sini berupa TEKS (= DEVICE_ID di
--     Config.h, mis. 'hydrosense-inlet-01'), id berupa bigint. Hubungan ke tabel
--     `devices` hanya "lunak": device_id = devices.name (tanpa foreign key, supaya
--     alat baru tidak ditolak sebelum didaftarkan).
--  2. UMUM (8 tabel): struktur groundtank (devices, sensors, ...) untuk gateway LoRa
--     dan alat lain. Pakai uuid.
--
--  * RLS di bagian akhir SENGAJA longgar (anon boleh baca/tulis tabel yang dipakai
--    dashboard & alat), sama seperti project lama. Perketat setelah gateway LoRa jalan.
--  * Kolom diambil dari kode, bukan dari dump schema lama. Kalau ada kolom lama yang
--    tidak terlihat di kode, tambahkan sebelum impor data.
--  * Impor data lama? Id memakai "generated by default", jadi bisa diisi eksplisit.
--    Setelah impor, samakan sequence-nya, mis.:
--      select setval(pg_get_serial_sequence('public."Hydrosense table"', 'id'),
--                    (select coalesce(max(id), 1) from public."Hydrosense table"));

-- =====================================================================
--  Fungsi bantu
-- =====================================================================
create or replace function public.set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

