-- =====================================================================
--  RLS (SEMENTARA, sama longgarnya dengan project Hydrosense lama)
--  HANYA untuk 12 tabel Hydrosense. Tabel groundtank (devices, sensors,
--  device_sensors, sensor_readings, tank_settings, device_tokens, settings_pin,
--  firmware_releases, tank_readings) TIDAK disentuh: RLS dan policy aslinya
--  dibiarkan, supaya keamanan groundtank tidak berubah saat migrasi ditambahkan.
--  Dashboard (github.io) dan alat memakai publishable/anon key tanpa login, jadi
--  anon harus bisa baca dan tulis tabel Hydrosense.
--  Tidak ada policy delete: dashboard dan firmware tidak menghapus apa pun.
--  TODO setelah LoRa: gateway pakai device_tokens, tulis lewat Edge Function,
--  dan perintah dari dashboard butuh login.
-- =====================================================================
do $$
declare
  t text;
  semua text[] := array[
    'Hydrosense table','water_level_readings','rain_gauge_readings','system_control',
    'device_status','auto_schedule','modbus_cmd','ph_calibration_cmd','calibration_samples',
    'tss_calibration_config','tss_calibration_samples','tss_hw_calibration_cmd'];
  tulis text[] := semua;
  ubah text[] := array[
    'device_status','auto_schedule','modbus_cmd','ph_calibration_cmd',
    'tss_hw_calibration_cmd'];
begin
  foreach t in array semua loop
    execute format('alter table public.%I enable row level security', t);
  end loop;

  foreach t in array semua loop
    execute format('drop policy if exists "anon_select" on public.%I', t);
    execute format('create policy "anon_select" on public.%I for select to anon, authenticated using (true)', t);
  end loop;

  foreach t in array tulis loop
    execute format('drop policy if exists "anon_insert" on public.%I', t);
    execute format('create policy "anon_insert" on public.%I for insert to anon, authenticated with check (true)', t);
  end loop;

  foreach t in array ubah loop
    execute format('drop policy if exists "anon_update" on public.%I', t);
    execute format('create policy "anon_update" on public.%I for update to anon, authenticated using (true) with check (true)', t);
  end loop;
end $$;
