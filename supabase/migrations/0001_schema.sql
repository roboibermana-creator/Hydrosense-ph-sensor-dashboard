-- diproses_at diisi otomatis saat firmware menutup perintah (Network.cpp tidak
-- mengirimnya).
create or replace function public.set_diproses_at() returns trigger
language plpgsql as $$
begin
  if new.status <> 'pending' and old.status = 'pending' and new.diproses_at is null then
    new.diproses_at := now();
  end if;
  return new;
end $$;
drop trigger if exists tss_hw_calibration_cmd_diproses on public.tss_hw_calibration_cmd;
create trigger tss_hw_calibration_cmd_diproses before update on public.tss_hw_calibration_cmd
  for each row execute function public.set_diproses_at();

