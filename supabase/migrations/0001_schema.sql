-- Kalau sensor_readings sudah ada dengan value bertipe text, ubah ke numeric.
-- Gagal (mis. ada isi non-angka) hanya memunculkan NOTICE; tipe dibiarkan.
do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'sensor_readings'
               and column_name = 'value' and data_type = 'text') then
    alter table public.sensor_readings
      alter column value type numeric using nullif(trim(value), '')::numeric;
  end if;
exception when others then
  raise notice 'sensor_readings.value tidak diubah ke numeric: %', sqlerrm;
end $$;

