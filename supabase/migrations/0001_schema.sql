-- Index dibuat di sini (setelah kolom lengkap). Satu index gagal tidak menghentikan
-- yang lain; pesannya muncul sebagai NOTICE. Dua index unique pertama dibutuhkan
-- upsert on_conflict=device_id kalau tabelnya dulu dibuat tanpa primary key.
do $$
declare s text;
begin
  foreach s in array array[
    'create unique index if not exists device_status_device_id_key on public.device_status (device_id)',
    'create unique index if not exists auto_schedule_device_id_key on public.auto_schedule (device_id)',
    'create index if not exists hydrosense_table_ts_idx on public."Hydrosense table" ("timestamp" desc)',
    'create index if not exists water_level_readings_ts_idx on public.water_level_readings ("timestamp" desc)',
    'create index if not exists rain_gauge_readings_ts_idx on public.rain_gauge_readings ("timestamp" desc)',
    'create index if not exists system_control_device_id_idx on public.system_control (device_id, id desc)',
    'create index if not exists modbus_cmd_pending_idx on public.modbus_cmd (status, id)',
    'create index if not exists ph_calibration_cmd_pending_idx on public.ph_calibration_cmd (status, id)',
    'create index if not exists calibration_samples_device_idx on public.calibration_samples (device_id, titik, aksi)',
    'create index if not exists tss_calibration_samples_idx on public.tss_calibration_samples (aksi, standard)',
    'create index if not exists tss_hw_calibration_cmd_pending_idx on public.tss_hw_calibration_cmd (status, id)'
  ] loop
    begin
      execute s;
    exception when others then
      raise notice 'Index dilewati: % (%)', s, sqlerrm;
    end;
  end loop;
end $$;

