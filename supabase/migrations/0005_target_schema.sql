-- HydroSense -> Supabase TUJUAN (project groundtank). Berdiri sendiri: TIDAK butuh
-- 0001-0004 (itu rantai migrasi untuk project Hydrosense lama).
-- Aman dijalankan ulang. Tidak menghapus atau mengubah tipe kolom tabel groundtank.
--
-- Yang ditambahkan ke project groundtank:
--   tabel baru : "Hydrosense table", calibration, device_commands, modbus_pin
--   kolom baru : devices (status alat + jadwal otomatis, menggantikan device_status)
--   RLS        : hanya untuk tabel baru + akses terbatas ke baris devices project 'hydrosense'
--
-- Data lama (kalau ada) diimpor manual dari project Hydrosense lama; urutan kolom di
-- tabel baru sama dengan hasil 0003/0004 di sana.

-- =====================================================================
--  1. Pembacaan sensor (pH, TSS, suhu, level air, hujan) -- 1 tabel
--  Baris pH/TSS : ph, tss, water_temperature, water_level
--  Baris level  : water_level + distance_cm   (dikirim tiap 5 detik)
--  Baris hujan  : rain_mm_per_hour + rain_mm_today
--  Dashboard memisahkan jenis baris dengan filter "kolom X tidak null".
-- =====================================================================
create table if not exists public."Hydrosense table" (
  id                bigint generated by default as identity primary key,
  "timestamp"       timestamptz not null default now(),
  ph                numeric,
  tss               numeric,
  water_temperature numeric,
  water_level       numeric,
  distance_cm       numeric,
  rain_mm_per_hour  numeric,
  rain_mm_today     numeric
);
create index if not exists hydrosense_table_ts_idx
  on public."Hydrosense table" ("timestamp" desc);

-- =====================================================================
--  2. Perintah dari dashboard ke alat -- 1 tabel
--  type     : 'control' | 'modbus' | 'ph_cal' | 'tss_hw'
--  perintah : modbus -> 'baca'|'tulis'; ph_cal/tss_hw -> nama perintah
--  params   : control {mode, valve_cmd, pump_cmd}
--             modbus  {slave_id, alamat, jumlah, nilai, tipe}
--             tss_hw  {nilai_target, nilai_aktual}
--  hasil    : modbus -> teks hasil; tss_hw -> {reg13, reg14}
--  'control' berupa LOG (baris baru tiap perintah): firmware mendeteksi perintah
--  baru lewat id yang naik (pengaman boot di ModeManual.cpp).
-- =====================================================================
create table if not exists public.device_commands (
  id          bigint generated by default as identity primary key,
  device_id   text,                         -- = devices.name (mis. 'hydrosense-inlet-01')
  type        text not null check (type in ('control', 'modbus', 'ph_cal', 'tss_hw')),
  perintah    text,
  params      jsonb,
  status      text not null default 'pending',
  hasil       jsonb,
  pesan       text,
  created_at  timestamptz not null default now(),
  diproses_at timestamptz
);
create index if not exists device_commands_pending_idx
  on public.device_commands (type, status, id);

create or replace function public.hydrosense_set_diproses_at() returns trigger
language plpgsql as $$
begin
  if new.status <> 'pending' and old.status = 'pending' and new.diproses_at is null then
    new.diproses_at := now();
  end if;
  return new;
end $$;
drop trigger if exists device_commands_diproses on public.device_commands;
create trigger device_commands_diproses before update on public.device_commands
  for each row execute function public.hydrosense_set_diproses_at();

-- =====================================================================
--  3. Kalibrasi pH + TSS -- 1 tabel
--  aksi 'kalibrasi' / 'verifikasi' = sampel (nilai, suhu, mv | ntu, raw_value)
--  aksi 'faktor'                   = faktor aktif TSS (slope, cal_offset, source,
--                                    points_count); baris terbaru = yang berlaku
-- =====================================================================
create table if not exists public.calibration (
  id           bigint generated by default as identity primary key,
  device_id    text,
  sensor       text not null check (sensor in ('ph', 'tss')),
  titik        text,                        -- ph: 'ph4'|'ph7'|'ph10'; tss: nama standard
  aksi         text,                        -- 'kalibrasi' | 'verifikasi' | 'faktor'
  sample_index integer,
  nilai        numeric,                     -- ph atau tss
  suhu         numeric,
  mv           numeric,                     -- hanya pH
  ntu          numeric,                     -- hanya TSS
  raw_value    numeric,                     -- hanya TSS
  slope        numeric,                     -- hanya aksi 'faktor'
  cal_offset   numeric,
  source       text,                        -- 'regression' | 'manual'
  points_count integer,
  created_at   timestamptz not null default now()
);
create index if not exists calibration_lookup_idx
  on public.calibration (sensor, aksi, titik);

-- =====================================================================
--  4. PIN Modbus (struktur sama dengan tabel di project Hydrosense lama)
--  Tanpa policy: anon TIDAK bisa membaca hash. Isi barisnya manual (SQL Editor) dari
--  project lama, mis.: insert into public.modbus_pin (pin_hash) values ('...');
-- =====================================================================
create table if not exists public.modbus_pin (
  id       integer generated by default as identity primary key,
  pin_hash text not null
);
alter table public.modbus_pin enable row level security;

-- =====================================================================
--  5. Status alat + jadwal otomatis: kolom baru di `devices`
--  (menggantikan device_status dan auto_schedule). 1 baris per alat; firmware dan
--  dashboard memakai: devices?name=eq.<DEVICE_ID>&project=eq.hydrosense
--  ip_address, mac_address, fw_version, ota_status sudah ada di devices groundtank.
--  `updated_at` devices berubah tiap update (trigger groundtank), jadi status pompa
--  memakai kolom sendiri: pump_updated_at.
-- =====================================================================
alter table public.devices
  add column if not exists mode              text,
  add column if not exists fase              text,
  add column if not exists next_cycle_s      integer,
  add column if not exists pump_on           boolean,
  add column if not exists pump_note         text,
  add column if not exists pump_updated_at   timestamptz,
  add column if not exists pompa_nyala       boolean,
  add column if not exists valve_buka        boolean,
  add column if not exists float_high        boolean,
  add column if not exists tss_raw           numeric,
  add column if not exists heartbeat_at      timestamptz,
  add column if not exists interval_detik    integer,
  add column if not exists pompa_detik       integer,
  add column if not exists valve_detik       integer,
  add column if not exists baca_sensor_detik integer,
  add column if not exists stabil_detik      integer,
  add column if not exists sampel_ms         integer,
  add column if not exists trim_persen       integer;

-- Baris alatnya harus ada: firmware memakai PATCH (tidak membuat baris baru).
insert into public.devices (name, project)
select 'hydrosense-inlet-01', 'hydrosense'
where not exists (
  select 1 from public.devices where name = 'hydrosense-inlet-01' and project = 'hydrosense');

-- =====================================================================
--  6. RLS
--  Dashboard (github.io) dan alat memakai anon key tanpa login, jadi anon boleh baca
--  dan tulis tabel Hydrosense. Tanpa policy delete.
--  Untuk `devices` HANYA baris project 'hydrosense' yang terbuka (baca + ubah);
--  baris groundtank tidak tersentuh. Policy bersifat menambah, policy groundtank
--  yang sudah ada tidak diubah.
--  TODO: perketat (login / Edge Function) setelah gateway LoRa jalan.
-- =====================================================================
do $$
declare t text;
begin
  foreach t in array array['Hydrosense table', 'device_commands', 'calibration'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "anon_select" on public.%I', t);
    execute format('create policy "anon_select" on public.%I for select to anon, authenticated using (true)', t);
    execute format('drop policy if exists "anon_insert" on public.%I', t);
    execute format('create policy "anon_insert" on public.%I for insert to anon, authenticated with check (true)', t);
  end loop;
end $$;

drop policy if exists "anon_update" on public.device_commands;
create policy "anon_update" on public.device_commands
  for update to anon, authenticated using (true) with check (true);

-- RLS pada `devices` SENGAJA tidak diaktifkan/dimatikan di sini (biarkan seperti di
-- groundtank): kalau RLS-nya mati, policy di bawah tidak berpengaruh; kalau menyala,
-- policy ini membuka baris hydrosense saja.
drop policy if exists "hydrosense_select" on public.devices;
create policy "hydrosense_select" on public.devices
  for select to anon, authenticated using (project = 'hydrosense');
drop policy if exists "hydrosense_update" on public.devices;
create policy "hydrosense_update" on public.devices
  for update to anon, authenticated
  using (project = 'hydrosense') with check (project = 'hydrosense');
