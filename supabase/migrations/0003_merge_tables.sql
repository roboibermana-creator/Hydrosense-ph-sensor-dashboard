-- HydroSense: gabungkan 5 tabel jadi 2.
--   modbus_cmd + ph_calibration_cmd + tss_hw_calibration_cmd -> device_commands
--   calibration_samples + tss_calibration_samples            -> calibration_samples
-- Jalankan SETELAH 0001. Hanya tabel Hydrosense: device_id berupa teks biasa, tanpa
-- foreign key atau trigger ke tabel `devices` (groundtank). Data lama disalin, lalu
-- tabel lama dihapus.
-- Firmware (src/Network.cpp) dan dashboard (index.html) harus yang sudah diperbarui.
-- Aman dijalankan ulang (tabel lama yang sudah hilang dilewati).

-- =====================================================================
--  1. device_commands
--  type     : 'modbus' | 'ph_cal' | 'tss_hw'
--  perintah : modbus -> 'baca'|'tulis'; lainnya -> nama perintah
--  params   : modbus {slave_id, alamat, jumlah, nilai, tipe}
--             tss_hw {nilai_target, nilai_aktual}
--  hasil    : modbus -> teks hasil; tss_hw -> {reg13, reg14}
-- =====================================================================
create table if not exists public.device_commands (
  id          bigint generated by default as identity primary key,
  device_id   text,
  type        text not null check (type in ('modbus', 'ph_cal', 'tss_hw')),
  perintah    text,
  params      jsonb,
  status      text not null default 'pending',
  hasil       jsonb,
  pesan       text,
  created_at  timestamptz not null default now(),
  diproses_at timestamptz
);
create index if not exists device_commands_pending_idx
  on public.device_commands (type, status, id);

-- diproses_at diisi otomatis saat firmware menutup perintah. Fungsinya didefinisikan
-- di sini juga supaya file ini tidak bergantung pada 0001.
create or replace function public.set_diproses_at() returns trigger
language plpgsql as $$
begin
  if new.status <> 'pending' and old.status = 'pending' and new.diproses_at is null then
    new.diproses_at := now();
  end if;
  return new;
end $$;

drop trigger if exists device_commands_diproses on public.device_commands;
create trigger device_commands_diproses before update on public.device_commands
  for each row execute function public.set_diproses_at();

-- =====================================================================
--  2. calibration_samples (pH + TSS)
--  Tabel pH lama bernama sama, jadi diganti namanya dulu, disalin, lalu dihapus.
-- =====================================================================
do $$
begin
  -- Hanya ganti nama kalau ini masih tabel pH lama (belum punya kolom `sensor`).
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'calibration_samples'
               and column_name = 'ph')
     and not exists (select 1 from information_schema.columns
                     where table_schema = 'public' and table_name = 'calibration_samples'
                       and column_name = 'sensor') then
    alter table public.calibration_samples rename to calibration_samples_old_ph;
  end if;
end $$;

create table if not exists public.calibration_samples (
  id           bigint generated by default as identity primary key,
  device_id    text,
  sensor       text not null check (sensor in ('ph', 'tss')),
  titik        text,                        -- ph: 'ph4'|'ph7'|'ph10'; tss: nama standard
  aksi         text,                        -- 'kalibrasi' | 'verifikasi'
  sample_index integer,
  nilai        numeric,                     -- ph atau tss
  suhu         numeric,
  mv           numeric,                     -- hanya pH
  ntu          numeric,                     -- hanya TSS
  raw_value    numeric,                     -- hanya TSS
  created_at   timestamptz not null default now()
);
create index if not exists calibration_samples_lookup_idx
  on public.calibration_samples (sensor, aksi, titik);

-- =====================================================================
--  3. Salin data lama, lalu hapus tabel lama
-- =====================================================================
do $$
begin
  if to_regclass('public.modbus_cmd') is not null then
    insert into public.device_commands
      (device_id, type, perintah, params, status, hasil, pesan, created_at)
    select device_id, 'modbus', aksi,
           jsonb_build_object('slave_id', slave_id, 'alamat', alamat, 'jumlah', jumlah,
                              'nilai', nilai, 'tipe', tipe),
           status, to_jsonb(hasil), pesan, created_at
      from public.modbus_cmd order by id;
    drop table public.modbus_cmd;
  end if;

  if to_regclass('public.ph_calibration_cmd') is not null then
    insert into public.device_commands (device_id, type, perintah, status, pesan, created_at)
    select device_id, 'ph_cal', perintah, status, pesan, created_at
      from public.ph_calibration_cmd order by id;
    drop table public.ph_calibration_cmd;
  end if;

  if to_regclass('public.tss_hw_calibration_cmd') is not null then
    insert into public.device_commands
      (device_id, type, perintah, params, status, hasil, pesan, created_at, diproses_at)
    select device_id, 'tss_hw', perintah,
           jsonb_build_object('nilai_target', nilai_target, 'nilai_aktual', nilai_aktual),
           status, jsonb_build_object('reg13', reg13, 'reg14', reg14), pesan,
           created_at, diproses_at
      from public.tss_hw_calibration_cmd order by id;
    drop table public.tss_hw_calibration_cmd;
  end if;

  if to_regclass('public.calibration_samples_old_ph') is not null then
    insert into public.calibration_samples
      (device_id, sensor, titik, aksi, sample_index, nilai, suhu, mv, created_at)
    select device_id, 'ph', titik, aksi, sample_index, ph, suhu, mv, created_at
      from public.calibration_samples_old_ph order by id;
    drop table public.calibration_samples_old_ph;
  end if;

  if to_regclass('public.tss_calibration_samples') is not null then
    insert into public.calibration_samples
      (device_id, sensor, titik, aksi, sample_index, nilai, suhu, ntu, raw_value, created_at)
    select device_id, 'tss', standard, aksi, sample_index, tss, suhu, ntu, raw_value, created_at
      from public.tss_calibration_samples order by id;
    drop table public.tss_calibration_samples;
  end if;
end $$;

-- =====================================================================
--  4. RLS (sama longgarnya dengan tabel Hydrosense lain; tanpa delete)
-- =====================================================================
alter table public.device_commands enable row level security;
alter table public.calibration_samples enable row level security;

drop policy if exists "anon_select" on public.device_commands;
create policy "anon_select" on public.device_commands for select to anon, authenticated using (true);
drop policy if exists "anon_insert" on public.device_commands;
create policy "anon_insert" on public.device_commands for insert to anon, authenticated with check (true);
drop policy if exists "anon_update" on public.device_commands;
create policy "anon_update" on public.device_commands for update to anon, authenticated using (true) with check (true);

drop policy if exists "anon_select" on public.calibration_samples;
create policy "anon_select" on public.calibration_samples for select to anon, authenticated using (true);
drop policy if exists "anon_insert" on public.calibration_samples;
create policy "anon_insert" on public.calibration_samples for insert to anon, authenticated with check (true);
